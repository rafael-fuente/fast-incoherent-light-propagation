"""Units for lengths in micrometres and powers in picowatts.

Write physical inputs with these constants, for example 532*nm or 2*mm.
Divide a length by m to display metres, or a power by W to display watts.
W/m**2 equals 1, so irradiance values keep their usual W/m² scale.
"""

um = 1.0
nm = 1e-3*um
mm = 1e3*um
cm = 1e4*um
m = 1e6*um
W = 1e12
